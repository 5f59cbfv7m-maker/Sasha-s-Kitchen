/// Стартовые наборы по регионам. Российский — `SeedData` (генерируется из
/// starter-data.md); остальные три собраны здесь вручную. Продукты набора —
/// всё, что нужно его рецептам, плюс пара базовых: так рецепт не может
/// сослаться на продукт, которого в наборе нет. Ключи — русские, как и у
/// российского набора: имена переводятся из таблицы `Seed`.
enum SeedSet: String, CaseIterable, Sendable {
    case russia, west, eastAsia, thailand

    /// Выбор в настройках; пусто — по региону устройства.
    static let key = "starterSet"

    static var current: SeedSet {
        SeedSet(rawValue: UserDefaults.standard.string(forKey: key) ?? "") ?? forRegion(Locale.current.region)
    }

    static func forRegion(_ region: Locale.Region?) -> SeedSet {
        switch region?.identifier ?? "" {
        case "RU", "BY", "KZ", "UA", "UZ", "KG", "TJ", "TM", "AM", "AZ", "GE", "MD": .russia
        case "JP", "KR", "CN", "TW", "HK", "MO": .eastAsia
        case "TH", "LA", "KH", "MM": .thailand
        default: .west
        }
    }

    var recipes: [SeedRecipe] {
        switch self {
        case .russia: SeedData.recipes
        case .west: Self.westRecipes
        case .eastAsia: Self.eastAsiaRecipes
        case .thailand: Self.thaiRecipes
        }
    }

    var products: [SeedProduct] {
        guard self != .russia else { return SeedData.products }
        let pool = Dictionary(SeedData.products.map { ($0.name, $0) } + Self.extraProducts.map { ($0.name, $0) },
                              uniquingKeysWith: { first, _ in first })
        var names: [String] = []
        for name in recipes.flatMap({ $0.ingredients.map(\.product) }) + Self.staples where !names.contains(name) {
            names.append(name)
        }
        return names.compactMap { pool[$0] }
    }

